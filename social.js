  /* الطزاجة بتتحسب مش بتتخزّن — تريند اتسجّل «شغّال» من ٣ أسابيع مش شغّال
     دلوقتي، والصف مش هيصحّي نفسه. الحالة اليدوية بتغلب بس لـdead وever. */
  function freshness(row, today) {
    if (row.state === "dead") return { state: "dead", label: "ميّت", days: null, why: "اتحدّد يدويًا إنه عدّى" };
    if (row.state === "ever") return { state: "ever", label: "دايم", days: null, why: "قالب مالوش تاريخ صلاحية" };
    const seen = row.first_seen ? new Date(row.first_seen).toISOString().slice(0, 10) : null;
    if (!seen) return { state: "watch", label: "متابعة", days: null, why: "مافيش تاريخ أول ظهور" };
    const age = daysBetween(seen, today);
    if (age > PLAYBOOK.sla.deadAfterDays) {
      return { state: "dead", label: "ميّت", days: age,
               why: `عدّى ${age} يوم من أول ظهور — تنفيذه دلوقتي أسوأ من السكوت` };
    }
    if (age > 7) return { state: "fading", label: "بيخفت", days: age, why: `${age} يوم من أول ظهور — لسه ينفع بزاوية مختلفة` };
    return { state: "live", label: "شغّال", days: age, why: `${age} يوم بس من أول ظهور — نفّذ فورًا` };
  }

  app.get("/api/social/trends", async (c) => {
    const err = await requireAdmin(c); if (err) return err;
    const today = riyadhToday();
    const trends = (await pool.query("SELECT * FROM social_trends ORDER BY sort, created_at")).rows;
    const ideas = (await pool.query("SELECT * FROM social_trend_ideas ORDER BY sort, created_at")).rows;

    const byTrend = {};
    for (const i of ideas) (byTrend[i.trend_id] ||= []).push(i);

    const out = trends.map((t) => {
      const f = freshness(t, today);
      const list = (byTrend[t.id] || []).map((i) => {
        const until = i.valid_until ? new Date(i.valid_until).toISOString().slice(0, 10) : null;
        /* فكرة بتبيع عرض عدّى تاريخه مابتتخفيش — بتتعلّم. الإخفاء الصامت
           بيخلّي حد يفتكر إن فيه باج ويرجّعها بالإيد. */
        const expired = !!(until && daysBetween(today, until) < 0);
        return {
          id: i.id, trendId: i.trend_id, title: i.title, platform: i.platform, format: i.format,
          hook: i.hook, dish: i.dish, priceNote: i.price_note, shots: i.shots,
          caption: i.caption, hashtags: i.hashtags, effortHours: i.effort_hours,
          status: i.status, note: i.note, assetNote: i.asset_note, validUntil: until,
          expired, sort: i.sort, updatedAt: i.updated_at,
        };
      });
      return {
        id: t.id, name: t.name, platform: t.platform, kind: t.kind,
        firstSeen: t.first_seen ? new Date(t.first_seen).toISOString().slice(0, 10) : null,
        state: t.state, verified: t.verified, source: t.source, note: t.note, sort: t.sort,
        freshness: f,
        ideas: list,
        totals: {
          all: list.length,
          approved: list.filter((i) => ["موافق", "تصوير", "جاهز", "تم"].includes(i.status)).length,
          pending: list.filter((i) => i.status === "مقترح").length,
          expired: list.filter((i) => i.expired).length,
        },
      };
    });

    return c.json({
      ok: true, today, trends: out, playbook: PLAYBOOK, statuses: IDEA_STATUS, states: TREND_STATE,
      totals: {
        trends: out.length,
        ideas: ideas.length,
        pending: out.reduce((a, t) => a + t.totals.pending, 0),
        readyNow: out.filter((t) => ["live", "ever"].includes(t.freshness.state)).reduce((a, t) => a + t.totals.all, 0),
      },
      publishing: { any: false, why: "بنك أفكار للمراجعة — مفيش نشر ولا جدولة من هنا. النقل للتقويم بالإيد." },
    });
  });

