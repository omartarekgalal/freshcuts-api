/* ── الفحص ─────────────────────────────────────────────────────────────────
   بيمشي على صفوف الكاتالوج (بعد ما الطبقة تتطبّق أو قبلها — الاتنين مفيدين)
   ويرجّع كل مخالفة. */
export function auditRows(rows) {
  const findings = [];
  const push = (level, r, msg, rule) =>
    findings.push({ level, id: r?.id ?? null, title: r?.title ?? "—", category: r?.category ?? "—", msg, rule: rule || null });

  const byCat = new Map();
  for (const r of rows) {
    if (!byCat.has(r.category)) byCat.set(r.category, []);
    byCat.get(r.category).push(r);
  }

  for (const r of rows) {
    const desc = String(r.description || "").trim();

    // ١) وصف فاضي أو بيكرّر الاسم — أسوأ حالة، العميل مش عارف حاجة.
    if (!desc) push("error", r, "الصنف من غير وصف خالص.");
    else if (norm(desc) === norm(r.title)) push("error", r, "الوصف بيكرّر الاسم بس — مش بيقول أي معلومة جديدة.");

    // ٢) قواعد الفئة.
    const rule = CATEGORY_RULES.find((x) => x.category === r.category);
    if (rule) {
      for (const m of rule.must || []) if (!hasAny(desc, m.any)) push("error", r, m.msg, rule.label);
      for (const m of rule.mustNot || []) if (hasAny(desc, m.any)) push("error", r, m.msg, rule.label);
    }
  }

  // ٣) وصف معلّب: نفس النص بالظبط لأكتر من صنف بعد ما نشيل اسم الصنف منه.
  //    ده اللي بيكشف الـ٩ أصناف بتوع المشاوي من غير ما نكتب أسماءهم هنا.
  const skeleton = new Map();
  for (const r of rows) {
    /* بنشيل **كل كلمة** من اسم الصنف من الوصف، مش اسم الصنف كنص واحد.
       الفرق مهم: اسم «كباب مشوي بالوزن» مش موجود حرفيًا جوّه وصفه، فمسح
       النص الكامل ماكانش بيشيل حاجة والهيكل كان بيفضل مختلف بين الأصناف —
       يعني الفاحص ماكانش بيكشف الجملة المعلّبة اللي اتعمل عشانها. */
    let bare = norm(String(r.description || ""));
    for (const tok of norm(r.title).split(" ")) if (tok.length > 1) bare = bare.split(tok).join(" ");
    bare = bare.replace(/\s+/g, " ").trim();
    if (!bare || bare.length < 12) continue;
    if (!skeleton.has(bare)) skeleton.set(bare, []);
    skeleton.get(bare).push(r);
  }
  for (const [bare, list] of skeleton) {
    if (list.length < 3) continue;
    push("warn", list[0], `${list.length} أصناف بتقول نفس الجملة المعلّبة بالظبط («${bare.slice(0, 60)}…») — وصف معلّب مش وصف صنف: ${list.map((x) => x.title).join("، ")}.`);
  }

  // ٤) الاسم بيوعد بمكوّن والوصف مش ذاكره.
  /* «جبن» مقصودة إنها مش هنا: كل صنف جبنة بيسمّي أنواعه بالاسم (موتزاريلا،
     شيدر، رومي) فالكلمة العامة بتطلّع بلاغ كداب على «كريب ميكس جبن». */
  const INGREDIENTS = ["مشروم", "بيكون", "شيدر", "موتزاريلا", "رانش", "بيبروني", "تونه", "جمبري", "بسطرمه", "ريش"];
  for (const r of rows) {
    for (const ing of INGREDIENTS) {
      if (mentionsWord(r.title, ing) && r.description && !mentionsWord(r.description, ing))
        push("warn", r, `الاسم فيه «${ing}» والوصف مش ذاكره — يا إما المكوّن ناقص من الوصف يا إما الاسم بيوعد بحاجة مش فيه.`);
    }
  }

  // ٥) قواعد على مستوى الفئة كلها (البرجر).
  for (const rule of CATEGORY_RULES) {
    if (!rule.categoryCheck) continue;
    const items = byCat.get(rule.category) || [];
    for (const msg of rule.categoryCheck(items))
      findings.push({ level: "error", id: null, title: rule.label, category: rule.category, msg, rule: rule.label });
  }

  // ٦) قاعدة الريش العابرة للفئات.
  for (const f of ribsChecks(rows))
    findings.push({ level: f.level, id: f.id, title: f.title, category: "—", msg: f.msg, rule: "الريش" });

  return findings;
}

/* ── تطبيق الطبقة ──────────────────────────────────────────────────────────
   بيرجّع { description, overlaid, source } لصنف واحد. بيتنادى من catalog.js
   وهو بيبني الصف، قبل ملاحظة «داخل الصالة». */
export function applyCopy(row) {
  const entry = COPY_OVERLAY.find((e) => String(e.id) === String(row.id));
  if (!entry) return { description: row.description, overlaid: false };
  let stillWrong = false;
  try { stillWrong = entry.when(row); } catch { stillWrong = false; }
  if (!stillWrong) return { description: row.description, overlaid: false, healed: true };
  return {
    description: typeof entry.description === "function" ? entry.description(row) : entry.description,
    overlaid: true,
    source: entry.source,
    why: entry.why,
  };
}

/* الأصناف اللي الطبقة لسه شغّالة عليها = بالظبط اللي عمر محتاج يصلّحها في
   الداشبورد. الدالة دي بتطلّع اللستة الجاهزة للّصق. */
export function pendingDashboardEdits(rows) {
  const out = [];
  for (const row of rows) {
    const r = applyCopy(row);
    if (r.overlaid) out.push({ id: row.id, title: row.title, category: row.category, was: row.description, shouldBe: r.description, source: r.source, why: r.why });
  }
  return out;
}
