/* Same normaliser as price-guard.js / claim-guard.js / asset-guard.js / ads.js.
   Matching has to stay identical across the system or each guard disagrees. */
export const norm = (s) => String(s || "")
  .replace(/[ً-ْـ]/g, "")
  .replace(/[أإآ]/g, "ا").replace(/ة/g, "ه").replace(/[ىئ]/g, "ي")
  .replace(/[^\p{L}\p{N}\s]/gu, " ")
  .replace(/\s+/g, " ").trim().toLowerCase();

const has = (text, word) => norm(text).includes(norm(word));
const hasAny = (text, words) => words.some((w) => has(text, w));

/* مطابقة **كلمة** مش جزء من كلمة — نفس منطق claim-guard.mentions().
   الفخ اللي وقعنا فيه هنا فعلاً: «كرانشي» جوّاها حروف «رانش»، فأي فحص
   بـincludes بيقول إن «كريب سوبر كرانشي» بيوعد بصوص رانش. أربع بلاغات كدّابة
   من خمسة كانت من ده. العربي بيلزق السوابق (و/ف/ب/ل/ك) و«ال» التعريف قدام
   الكلمة، فمسموح بيهم قبلها، والحد الآخر لازم يكون مسافة أو نهاية. */
function mentionsWord(text, word) {
  const w = norm(word);
  if (!w) return false;
  const esc = w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp("(^| )[وفبلك]*(ال)?" + esc + "( |$)").test(" " + norm(text) + " ");
}

